/* md.js — markdown content discovery + frontmatter parsing.
 * No external library required for parsing; for rendering of post bodies
 * we use marked.min.js loaded from CDN on the post pages that need it.
 */

/**
 * Split a markdown string into a frontmatter object and a body string.
 * Frontmatter is YAML-like but parsed manually with a tiny ruleset:
 *   - Starts with --- on the first line.
 *   - Ends with --- on its own line.
 *   - Each line is `key: value`.
 *   - Values starting with [ are parsed as comma-separated arrays (simple).
 *   - Quoted values ("..." or '...') are unwrapped.
 *   - All values are stored as strings (or arrays of strings).
 */
export function parseFrontmatter(raw) {
  if (!raw.startsWith('---')) {
    return { frontmatter: {}, body: raw };
  }
  const end = raw.indexOf('\n---', 3);
  if (end === -1) {
    return { frontmatter: {}, body: raw };
  }
  const fmText = raw.slice(3, end).trim();
  const body = raw.slice(end + 4).replace(/^\r?\n/, '');
  const fm = {};

  let currentKey = null;
  let buffer = [];

  const flush = () => {
    if (currentKey === null) return;
    let value = buffer.join('\n').trim();
    if (value.startsWith('[') && value.endsWith(']')) {
      value = value
        .slice(1, -1)
        .split(',')
        .map((v) => v.trim().replace(/^['"]|['"]$/g, ''))
        .filter(Boolean);
    } else if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    fm[currentKey] = value;
    currentKey = null;
    buffer = [];
  };

  for (const line of fmText.split(/\r?\n/)) {
    // A new top-level key is `keyword: ...` at column 0 (no leading whitespace).
    const m = /^([A-Za-z][A-Za-z0-9_]*):\s?(.*)$/.exec(line);
    if (m) {
      flush();
      currentKey = m[1];
      buffer = [m[2]];
    } else {
      // Continuation lines (indented or part of a multi-line value).
      buffer.push(line);
    }
  }
  flush();

  return { frontmatter: fm, body };
}

/**
 * Discover markdown files in a content directory.
 *
 * We always try BOTH sources and union them:
 *   1. /<dir>/manifest.json — generated by scripts/regenerate.mjs. Source of
 *      truth for the canonical sort order. Always present in production.
 *   2. /<dir>/ — Python http.server's directory listing. Only available in
 *      local dev. Lets brand-new .md files appear immediately without
 *      re-running the regenerate script.
 *
 * The merged result keeps manifest order (so the site looks the same as
 * production) and appends any extra slugs found in the directory listing.
 * Returns an array of slugs (e.g. "first-principles").
 */
export async function listMarkdownFiles(dir) {
  const [manifestSlugs, dirSlugs] = await Promise.all([
    fetchManifestSlugs(dir),
    fetchDirectoryListingSlugs(dir),
  ]);

  if (manifestSlugs.length === 0 && dirSlugs.length === 0) return [];

  const seen = new Set();
  const out = [];
  for (const slug of manifestSlugs) {
    if (!seen.has(slug)) {
      seen.add(slug);
      out.push(slug);
    }
  }
  for (const slug of dirSlugs) {
    if (!seen.has(slug)) {
      seen.add(slug);
      out.push(slug);
    }
  }
  return out;
}

async function fetchManifestSlugs(dir) {
  try {
    const res = await fetch(`/${dir}/manifest.json`, { cache: 'no-store' });
    if (!res.ok) return [];
    const data = await res.json();
    return Array.isArray(data.slugs) ? data.slugs : [];
  } catch {
    return [];
  }
}

async function fetchDirectoryListingSlugs(dir) {
  try {
    const res = await fetch(`/${dir}/`);
    if (!res.ok) return [];
    const html = await res.text();
    // Static hosts (production) typically don't return a parseable listing —
    // skip silently when there's no content-type-friendly HTML to scrape.
    if (!/<a [^>]*href=/i.test(html)) return [];
    const slugs = [];
    const re = /href="([^"]+\.md)"/g;
    let m;
    while ((m = re.exec(html))) {
      const name = decodeURIComponent(m[1]).replace(/^.*\//, '');
      if (name === 'README.md' || name.startsWith('_')) continue;
      slugs.push(name.replace(/\.md$/, ''));
    }
    return slugs;
  } catch {
    return [];
  }
}

/** Fetch a single markdown post and return { frontmatter, body, slug }. */
export async function fetchPost(dir, slug) {
  const res = await fetch(`/${dir}/${slug}.md`, { cache: 'no-store' });
  if (!res.ok) throw new Error(`Failed to load ${dir}/${slug}.md (${res.status})`);
  const raw = await res.text();
  const { frontmatter, body } = parseFrontmatter(raw);
  return { slug, frontmatter, body };
}

/** Fetch every markdown file in a directory in parallel. */
export async function fetchAll(dir) {
  const slugs = await listMarkdownFiles(dir);
  const items = await Promise.all(
    slugs.map(async (slug) => {
      try {
        return await fetchPost(dir, slug);
      } catch (err) {
        console.warn('skip', dir, slug, err);
        return null;
      }
    })
  );
  return items.filter(Boolean);
}

/**
 * Sort posts by `updated` (DD.MM.YYYY) descending, falling back to the legacy
 * `date` field. Items without either go last.
 */
export function sortByDateDesc(items) {
  const toMs = (s) => {
    if (!s) return -Infinity;
    const m = /^(\d{2})\.(\d{2})\.(\d{4})$/.exec(s);
    if (!m) return -Infinity;
    return new Date(Number(m[3]), Number(m[2]) - 1, Number(m[1])).getTime();
  };
  const dateOf = (fm) => fm.updated || fm.date || '';
  return items
    .slice()
    .sort((a, b) => toMs(dateOf(b.frontmatter)) - toMs(dateOf(a.frontmatter)));
}

/** Tiny HTML escaper for safe insertion. */
export function esc(s) {
  return String(s ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}
