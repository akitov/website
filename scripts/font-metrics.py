#!/usr/bin/env python3
"""About Beige's left side bearings at the weights the site sets.

Writes scripts/vendor/about-beige/side-bearings.json: for every weight token in
styles.css (--w-light, --w-normal, ... --w-regular), each character's left side
bearing (the glyph's xMin, in font units; 1000 units = 1em) in the variable
font instanced at that weight. scripts/build.mjs uses it to pull drop caps and
headings left by their first glyph's side bearing, so their ink starts on the
text column's edge (see "Optical left edge" in styles.css).

Run after changing a weight token or the font (needs fonttools and brotli):
    python3 -m venv /tmp/fv && /tmp/fv/bin/pip install fonttools brotli
    /tmp/fv/bin/python scripts/font-metrics.py
"""
import json
import os
import re

from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONT = os.path.join(ROOT, 'assets', 'fonts', 'AboutBeige.woff2')
OUT = os.path.join(ROOT, 'scripts', 'vendor', 'about-beige', 'side-bearings.json')


def main():
    css = open(os.path.join(ROOT, 'styles.css'), encoding='utf-8').read()
    weights = sorted({int(w) for w in re.findall(r'--w-[\w-]+:\s*(\d+)\s*;', css)})
    tables = {}
    for w in weights:
        font = instancer.instantiateVariableFont(TTFont(FONT), {'wght': w, 'MONO': 0})
        glyf = font['glyf']
        row = {}
        for cp, name in sorted(font.getBestCmap().items()):
            g = glyf[name]
            if g.numberOfContours == 0:
                continue  # space and other empty glyphs
            g.recalcBounds(glyf)
            row[chr(cp)] = g.xMin
        tables[str(w)] = row
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write('{\n  "_": "About Beige left side bearings (glyph xMin, font units, upm 1000) by weight. Generated by scripts/font-metrics.py; do not edit.",\n')
        f.write(',\n'.join(f'  "{w}": {json.dumps(t, ensure_ascii=False, separators=(",", ":"))}' for w, t in tables.items()))
        f.write('\n}\n')
    print(f'{OUT}: weights {", ".join(map(str, weights))}, {len(next(iter(tables.values())))} characters')


if __name__ == '__main__':
    main()
